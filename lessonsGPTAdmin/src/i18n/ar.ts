export function statusLabel(status: JobStatus | string): string {
  return t.status[status as JobStatus] ?? String(status).replace(/_/g, ' ')
}

export function stageLabel(stage: string | null | undefined): string {
  if (!stage) return t.common.dash
  return t.stages[stage] ?? stage.replace(/_/g, ' ')
}

export function formatDateAr(iso: string | null | undefined): string {
  if (!iso) return t.common.dash
  return new Date(iso).toLocaleString('ar', {
    dateStyle: 'medium',
    timeStyle: 'short',
  })
}
